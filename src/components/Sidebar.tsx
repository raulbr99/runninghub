export default function Sidebar() {
  const pathname = usePathname();
  const [conversations, setConversations] = useState<Conversation[]>([]);
  const [loading, setLoading] = useState(true);
  const [isOpen, setIsOpen] = useState(false);
  const [expandedSections, setExpandedSections] = useState<Set<string>>(() => {
    const initial = new Set<string>();
    navSections.forEach((section) => {
      if (section.defaultOpen) initial.add(section.title);
    });
    return initial;
  });

  useEffect(() => {
    loadConversations();
  }, []);

  useEffect(() => {
    setIsOpen(false);
  }, [pathname]);

  // Auto-expand section containing active route
  useEffect(() => {
    navSections.forEach((section) => {
      if (section.items.some((item) => item.href === pathname)) {
        setExpandedSections((prev) => new Set([...prev, section.title]));
      }
    });
  }, [pathname]);

  const loadConversations = async () => {
    try {
      const res = await fetch('/api/conversations');
      if (res.ok) {
        const data = await res.json();
        setConversations(data);
      }
    } catch (error) {
      console.error('Error loading conversations:', error);
    } finally {
      setLoading(false);
    }
  };

  const toggleSection = (title: string) => {
    setExpandedSections((prev) => {
      const next = new Set(prev);
      if (next.has(title)) {
        next.delete(title);
      } else {
        next.add(title);
      }
      return next;
    });
  };

  const deleteConversation = async (id: string, e: React.MouseEvent) => {
    e.preventDefault();
    e.stopPropagation();
    if (!confirm('Eliminar esta conversacion?')) return;
    try {
      await fetch(`/api/conversations?id=${id}`, { method: 'DELETE' });
      setConversations(conversations.filter((c) => c.id !== id));
    } catch (error) {
      console.error('Error deleting conversation:', error);
    }
  };

  const formatDate = (dateString: string) => {
    const date = new Date(dateString);
    const now = new Date();
    const diffDays = Math.floor((now.getTime() - date.getTime()) / (1000 * 60 * 60 * 24));
    if (diffDays === 0) return 'Hoy';
    if (diffDays === 1) return 'Ayer';
    if (diffDays < 7) return `${diffDays}d`;
    return date.toLocaleDateString('es-ES', { day: 'numeric', month: 'short' });
  };

  return (
    <>
      {/* Mobile menu button */}
      <button
        onClick={() => setIsOpen(true)}
        className="md:hidden fixed top-4 left-4 z-50 p-2.5 bg-zinc-900 rounded-lg border border-zinc-800"
      >
        <svg className="w-5 h-5 text-zinc-400" fill="none" stroke="currentColor" viewBox="0 0 24 24">
          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={1.5} d="M3.75 6.75h16.5M3.75 12h16.5m-16.5 5.25h16.5" />
        </svg>
      </button>

      {/* Overlay */}
      {isOpen && (
        <div
          className="md:hidden fixed inset-0 bg-black/60 backdrop-blur-sm z-40"
          onClick={() => setIsOpen(false)}
        />
      )}

      {/* Sidebar */}
      <aside
        className={`w-56 bg-zinc-950 border-r border-zinc-800/50 h-screen fixed left-0 top-0 flex flex-col z-50 transition-transform duration-300 ${
          isOpen ? 'translate-x-0' : '-translate-x-full md:translate-x-0'
        }`}
      >
        {/* Logo */}
        <div className="p-4 border-b border-zinc-800/50">
          <div className="flex items-center justify-between">
            <div className="flex items-center gap-2">
              <div className="w-8 h-8 rounded-lg bg-emerald-500/10 border border-emerald-500/20 flex items-center justify-center">
                <svg className="w-4 h-4 text-emerald-500" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                  <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={1.5} d="M3.75 13.5l10.5-11.25L12 10.5h8.25L9.75 21.75 12 13.5H3.75z" />
                </svg>
              </div>
              <span className="font-semibold text-zinc-100 text-sm">RunningHub</span>
            </div>
            <button
              onClick={() => setIsOpen(false)}
              className="md:hidden p-1 text-zinc-500 hover:text-zinc-300 rounded"
            >
              <svg className="w-4 h-4" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={1.5} d="M6 18L18 6M6 6l12 12" />
              </svg>
            </button>
          </div>
        </div>

        {/* Navigation */}
        <nav className="flex-1 overflow-y-auto p-2">
          {navSections.map((section) => {
            const isExpanded = expandedSections.has(section.title);
            const hasActiveItem = section.items.some((item) => item.href === pathname);

            return (
              <div key={section.title} className="mb-1">
                <button
                  onClick={() => toggleSection(section.title)}
                  className={`w-full flex items-center justify-between px-2 py-1.5 text-[10px] font-medium uppercase tracking-wider rounded transition-colors ${
                    hasActiveItem ? 'text-emerald-400' : 'text-zinc-500 hover:text-zinc-400'
                  }`}
                >
                  <span>{section.title}</span>
                  <svg
                    className={`w-3 h-3 transition-transform ${isExpanded ? 'rotate-180' : ''}`}
                    fill="none"
                    stroke="currentColor"
                    viewBox="0 0 24 24"
                  >
                    <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M19 9l-7 7-7-7" />
                  </svg>
                </button>

                {isExpanded && (
                  <div className="mt-0.5 space-y-0.5">
                    {section.items.map((item) => {
                      const isActive = pathname === item.href;
                      return (
                        <Link
                          key={item.href}
                          href={item.href}
                          className={`flex items-center gap-2 px-2 py-1.5 rounded-md text-xs transition-all ${
                            isActive
                              ? 'bg-emerald-500/10 text-emerald-400'
                              : 'text-zinc-400 hover:text-zinc-200 hover:bg-zinc-800/50'
                          }`}
                        >
                          {item.icon}
                          <span>{item.label}</span>
                        </Link>
                      );
                    })}
                  </div>
                )}
              </div>
            );
          })}
        </nav>

        {/* Conversations (collapsed) */}
        <div className="border-t border-zinc-800/50">
          <details className="group">
            <summary className="flex items-center justify-between px-3 py-2 text-[10px] font-medium text-zinc-500 uppercase tracking-wider cursor-pointer hover:text-zinc-400">
              <span>Historial ({conversations.length})</span>
              <svg className="w-3 h-3 transition-transform group-open:rotate-180" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M19 9l-7 7-7-7" />
              </svg>
            </summary>
            <div className="max-h-32 overflow-y-auto px-2 pb-2">
              {loading ? (
                <div className="flex justify-center py-2">
                  <div className="w-3 h-3 border-2 border-emerald-500 border-t-transparent rounded-full animate-spin" />
                </div>
              ) : conversations.length === 0 ? (
                <p className="text-[10px] text-center text-zinc-600 py-2">Sin conversaciones</p>
              ) : (
                <div className="space-y-0.5">
                  {conversations.slice(0, 5).map((conv) => (
                    <Link
                      key={conv.id}
                      href={`/coach?conversation=${conv.id}`}
                      className="group/item flex items-center justify-between px-2 py-1 rounded text-[11px] text-zinc-400 hover:bg-zinc-800/50"
                    >
                      <span className="truncate flex-1">{conv.title}</span>
                      <span className="text-[9px] text-zinc-600 ml-1">{formatDate(conv.updatedAt)}</span>
                    </Link>
                  ))}
                </div>
              )}
            </div>
          </details>
        </div>
      </aside>
    </>
  );
}
